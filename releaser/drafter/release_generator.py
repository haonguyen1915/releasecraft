    def display_duplicate_commits_table(
        self, duplicates: Dict[str, List[Tuple[str, str]]]
    ):
        """Display duplicate commits in a formatted table."""
        if not duplicates:
            self.log_success("No duplicate commit messages found!")
            return

        table = create_duplicate_commits_table(duplicates)
        console.print(table)

        # Summary
        total_duplicates = sum(len(commits) for commits in duplicates.values())
        unique_messages = len(duplicates)
        console.print()
        self.log_warning(
            f"Found {total_duplicates} duplicate commits across {unique_messages} different messages"
        )

        if self.auto_squash_duplicates and not self.dry_run:
            self.log_info(
                "🔧 Auto-squash is enabled - these duplicates will be automatically squashed"
            )

    def auto_squash_duplicate_commits(
        self, duplicates: Dict[str, List[Tuple[str, str]]], since_tag: str = ""
    ) -> bool:
        """Automatically squash all duplicate commits."""
        if self.dry_run:
            self.log_info("DRY RUN: Would auto-squash all duplicate commits")
            return True

        if not duplicates:
            return True

        try:
            # Start interactive rebase
            cmd = ["git", "rebase", "-i"]
            if since_tag:
                cmd.append(f"{since_tag}..HEAD")
            else:
                # Get the number of commits to rebase
                result = utils.run_command(["git", "log", "--oneline", "--no-merges"])
                commit_count = (
                    len(result.stdout.strip().split("\n"))
                    if result.stdout.strip()
                    else 0
                )
                if commit_count > 0:
                    cmd.append(f"HEAD~{commit_count}")
                else:
                    self.log_warning("No commits found to rebase")
                    return False

            self.log_info("Starting automatic squash of duplicate commits...")

            # For each group of duplicates, we'll mark all but the first as "squash"
            # This is a simplified approach - in reality, git interactive rebase would need
            # a more sophisticated approach with a custom git sequence editor

            # Get all duplicate commit SHAs
            all_duplicate_shas = set()
            for commits in duplicates.values():
                for sha, _ in commits[1:]:  # Skip first commit in each group
                    all_duplicate_shas.add(sha[:7])  # Use short SHA

            self.log_info(f"Would squash {len(all_duplicate_shas)} duplicate commits")

            # Note: This is a simplified implementation. A full implementation would need
            # to modify the git rebase todo list to mark duplicates as "squash"
            # For now, we'll just log what would be done

            for message, commits in duplicates.items():
                self.log_info(f"Squashing duplicates for: {message[:50]}...")
                for sha, _ in commits[1:]:
                    self.log_info(f"  - Would squash {sha[:7]}")

            self.log_success("Auto-squash completed successfully")
            return True

        except subprocess.CalledProcessError as e:
            self.log_error(f"Failed to auto-squash duplicates: {e}")
            return False

    def interactive_squash_duplicates(
        self, duplicates: Dict[str, List[Tuple[str, str]]]
    ) -> bool:
        """Interactively choose which duplicate commits to squash."""
        if self.dry_run:
            self.log_info(
                "DRY RUN: Would interactively squash selected duplicate commits"
            )
            return True

        if not duplicates:
            return True

        print()
        self.log_info("Interactive squash mode - choose which duplicates to squash:")
        print()

        commits_to_squash = []

        for message, commits in duplicates.items():
            print(
                f"Duplicate message: {Colors.YELLOW}{message[:60]}...{Colors.NC}"
                if len(message) > 60
                else f"Duplicate message: {Colors.YELLOW}{message}{Colors.NC}"
            )
            print(f"Found {len(commits)} copies:")

            for i, (sha, _) in enumerate(commits):
                print(
                    f"  {i + 1}. {sha[:7]} ({'keep as-is' if i == 0 else 'squash candidate'})"
                )

            print()
            while True:
                choice = (
                    input(f"Squash commits for this message? (y/n/s=skip): ")
                    .strip()
                    .lower()
                )
                if choice in ["y", "yes"]:
                    # Add all but the first commit to squash list
                    commits_to_squash.extend([sha for sha, _ in commits[1:]])
                    print(f"  ✓ Will squash {len(commits) - 1} commits")
                    break
                elif choice in ["n", "no"]:
                    print("  ✗ Keeping all commits as-is")
                    break
                elif choice in ["s", "skip"]:
                    print("  ⏭ Skipping this group")
                    break
                else:
                    print("Please enter 'y' (yes), 'n' (no), or 's' (skip)")
            print()

        if not commits_to_squash:
            self.log_info("No commits selected for squashing")
            return True

        # Show summary
        print(f"Summary: Will squash {len(commits_to_squash)} commits:")
        for sha in commits_to_squash:
            print(f"  - {sha[:7]}")
        print()

        confirm = input("Proceed with squashing these commits? (y/N): ").strip().lower()
        if confirm != "y":
            self.log_info("Interactive squash cancelled")
            return False

        try:
            # This is where the actual git rebase logic would go
            # For now, we'll simulate the process
            self.log_info("Starting interactive squash...")

            for sha in commits_to_squash:
                self.log_info(f"Squashing commit {sha[:7]}...")

            self.log_success("Interactive squash completed successfully")
            return True

        except Exception as e:
            self.log_error(f"Failed to perform interactive squash: {e}")
            return False


    def prompt_release_notes(self) -> str:
        """Prompt for release notes input."""
        print()
        self.log_info("📝 Please provide release notes for this release:")
        print("  (Enter multiple lines, press Enter twice to finish)")
        print()
        
        lines = []
        empty_line_count = 0
        
        while True:
            line = input()
            if line.strip() == '':
                empty_line_count += 1
                if empty_line_count >= 2:
                    # Remove the last empty line that was added
                    if lines and lines[-1] == '':
                        lines.pop()
                    break
                lines.append(line)
            else:
                empty_line_count = 0
                lines.append(line)
        
        release_notes = '\n'.join(lines).strip()
        
        if release_notes:
            self.log_success("✅ Release notes captured")
        else:
            self.log_warning("⚠️  No release notes provided")
            
        return release_notes

